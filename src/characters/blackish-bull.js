// ---------------------------------------------------------------------------
// tiny procedural-model helpers (inline — character files are self-contained)
// ---------------------------------------------------------------------------
function lamb(color, opts = {}) {
  return new THREE.MeshLambertMaterial({ color, flatShading: true, ...opts })
}

function box(w, h, d, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function sph(r, material, x = 0, y = 0, z = 0, sx = 1, sy = 1, sz = 1) {
  const m = new THREE.Mesh(new THREE.SphereGeometry(r, 10, 8), material)
  m.position.set(x, y, z)
  m.scale.set(sx, sy, sz)
  return m
}

function cyl(rTop, rBottom, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rTop, rBottom, h, 8, 1), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function cone(r, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.ConeGeometry(r, h, 5), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function pivot(parent, x = 0, y = 0, z = 0) {
  const g = new THREE.Group()
  g.position.set(x, y, z)
  parent.add(g)
  return g
}

// static wrapper: bakes a base rotation between an animated bone and its meshes,
// so every animated bone starts at rotation (0,0,0) = bind pose.
function bent(parent, rz = 0, rx = 0, ry = 0) {
  const g = new THREE.Group()
  g.rotation.set(rx, ry, rz)
  parent.add(g)
  return g
}

// one glowing candlestick marking (body + wick share one emissive material)
function addMark(parent, markMats, x, y, z, h, up, hot = false) {
  const bodyHex = up ? C.green : C.red
  const emHex = up ? (hot ? C.greenEmHot : C.greenEm) : (hot ? C.redEmHot : C.redEm)
  const m = lamb(bodyHex)
  m.emissive = new THREE.Color(emHex)
  m.userData.baseEm = emHex
  markMats.push(m)
  parent.add(box(0.045, h, 0.1, m, x, y, z))
  parent.add(box(0.04, h * 1.7, 0.04, m, x, y, z))
}

// ---------------------------------------------------------------------------
// model — faces +X, feet at y=0, ~2.5 m tall (x1.15 for the unchained variant)
// ---------------------------------------------------------------------------
function buildBullModel(costume = 0, opts = {}) {
  const un = !!opts.unchained
  const group = new THREE.Group()
  const bones = {}
  const markMats = []

  const hideM = lamb(C.hide)
  const hideDarkM = lamb(C.hideDark)
  const muzzleM = lamb(C.muzzle)
  const hoofM = lamb(C.hoof)
  const hornM = lamb(C.silver)
  const hornDarkM = lamb(C.silverDark)
  const jacketM = lamb(C.jacket)
  const trimM = lamb(costume === 1 ? C.gold : C.jacketTrim)
  const visorM = lamb(un ? C.visorFaceRed : costume === 1 ? C.visorFaceAlt : C.visorFace)
  visorM.emissive = new THREE.Color(un ? C.visorEmRed : costume === 1 ? C.visorEmAlt : C.visorEm)
  visorM.userData.baseEm = visorM.emissive.getHex()

  // --- hips -----------------------------------------------------------------
  const hips = pivot(group, 0, 1.15, 0)
  bones.hips = hips
  hips.add(sph(0.38, hideM, 0, 0.0, 0, 1.05, 0.72, 1.1))

  // tail (extra bone, spring-follow secondary motion)
  const tail = pivot(hips, -0.36, 0.08, 0)
  bones.tail = tail
  const tailW = bent(tail, 2.3)
  tailW.add(cyl(0.035, 0.025, 0.42, hideDarkM, 0, -0.21, 0))
  tailW.add(sph(0.07, hoofM, 0, -0.44, 0, 1, 1.35, 1))

  // --- legs — thick columns ending in split hooves ---------------------------
  for (const side of [1, -1]) {
    const leg = pivot(hips, 0, -0.05, 0.26 * side)
    bones[side === 1 ? 'legL' : 'legR'] = leg
    leg.add(cyl(0.2, 0.22, 0.6, hideM, 0, -0.32, 0))
    const shin = pivot(leg, 0, -0.62, 0)
    bones[side === 1 ? 'shinL' : 'shinR'] = shin
    shin.add(cyl(0.17, 0.15, 0.4, hideDarkM, 0, -0.2, 0))
    shin.add(box(0.32, 0.18, 0.26, hoofM, 0.05, -0.39, 0))
    shin.add(box(0.1, 0.1, 0.24, hideDarkM, 0.2, -0.34, 0)) // hoof split ridge
  }

  // --- torso — broad chest, sleeveless combat jacket -------------------------
  const torso = pivot(hips, 0, 0.15, 0)
  bones.torso = torso
  torso.add(sph(0.56, hideM, 0.05, 0.42, 0, 1.05, 0.95, 1.28)) // massive chest
  torso.add(sph(0.4, hideDarkM, -0.02, 0.05, 0, 0.95, 0.7, 1.05)) // gut plate

  if (!un) {
    // black sleeveless combat jacket: open front, side + back panels, collar
    torso.add(box(0.34, 0.92, 0.3, jacketM, -0.02, 0.42, 0.62))
    torso.add(box(0.34, 0.92, 0.3, jacketM, -0.02, 0.42, -0.62))
    torso.add(box(0.3, 0.95, 1.1, jacketM, -0.42, 0.42, 0))
    torso.add(box(0.5, 0.12, 1.28, jacketM, -0.08, 0.92, 0))
    torso.add(box(0.24, 0.16, 0.5, trimM, 0.28, 0.92, 0)) // collar trim
    torso.add(box(0.32, 0.1, 0.32, trimM, -0.02, -0.02, 0.62)) // hem tab L
    torso.add(box(0.32, 0.1, 0.32, trimM, -0.02, -0.02, -0.62)) // hem tab R
    // glowing green candlesticks down the exposed chest
    addMark(torso, markMats, 0.56, 0.68, 0.16, 0.14, true)
    addMark(torso, markMats, 0.58, 0.5, 0.0, 0.2, true)
    addMark(torso, markMats, 0.56, 0.3, -0.16, 0.26, true)
    addMark(torso, markMats, 0.5, 0.08, 0.08, 0.18, true)
  } else {
    // UNCHAINED: jacket off — bare chest wearing the full candlestick chart
    let up = true
    for (let i = 0; i < 4; i++) {
      for (let j = 0; j < 2; j++) {
        addMark(torso, markMats, 0.58 - j * 0.06, 0.76 - i * 0.22, -0.3 + j * 0.34 + (i % 2) * 0.12,
          0.12 + ((i + j) % 3) * 0.07, up, true)
        up = !up
      }
    }
    addMark(torso, markMats, 0.5, -0.04, 0.0, 0.16, false, true)
  }

  // --- arms — huge shoulders, heavy rounded fists ----------------------------
  for (const side of [1, -1]) {
    const arm = pivot(torso, 0.02, 0.62, 0.6 * side)
    bones[side === 1 ? 'armL' : 'armR'] = arm
    arm.add(sph(0.22, un ? hideM : jacketM, 0, 0.04, 0.06 * side)) // shoulder ball / jacket cap
    if (!un) arm.add(box(0.3, 0.1, 0.3, trimM, 0, 0.14, 0.04 * side))
    arm.add(cyl(0.15, 0.13, 0.36, hideM, 0, -0.24, 0))
    addMark(arm, markMats, 0.14, -0.26, 0.02 * side, 0.12, true, un)
    const fore = pivot(arm, 0, -0.46, 0)
    bones[side === 1 ? 'forearmL' : 'forearmR'] = fore
    fore.add(cyl(0.13, 0.12, 0.32, hideDarkM, 0, -0.16, 0))
    addMark(fore, markMats, 0.12, -0.14, 0, 0.1, side === 1, un)
    fore.add(sph(0.24, hideDarkM, 0.02, -0.4, 0, 1.05, 0.95, 1.0)) // heavy rounded fist
    fore.add(box(0.16, 0.1, 0.3, hoofM, 0.14, -0.34, 0)) // knuckle plate
  }

  // --- head — blocky bull skull, mirrored glowing visor, silver horns --------
  const head = pivot(torso, 0.05, 0.82, 0)
  bones.head = head
  head.add(box(0.52, 0.44, 0.46, hideDarkM, 0.08, 0.14, 0))
  head.add(box(0.36, 0.3, 0.36, muzzleM, 0.38, -0.02, 0)) // muzzle
  head.add(box(0.06, 0.08, 0.08, hoofM, 0.56, 0.0, 0.09)) // nostril L
  head.add(box(0.06, 0.08, 0.08, hoofM, 0.56, 0.0, -0.09)) // nostril R
  if (costume === 1 && !un) {
    const ring = new THREE.Mesh(new THREE.TorusGeometry(0.09, 0.025, 5, 8), lamb(C.gold))
    ring.position.set(0.56, -0.14, 0)
    head.add(ring)
  }
  // mirrored rectangular visor (glowing)
  head.add(box(0.1, 0.18, 0.44, visorM, 0.34, 0.22, 0))
  head.add(box(0.08, 0.05, 0.5, hoofM, 0.32, 0.33, 0)) // visor brow frame
  // silver geometric horns — two faceted segments per side
  for (const side of [1, -1]) {
    const hw = bent(pivot(head, 0.04, 0.3, 0.24 * side), 0, 0.9 * side, 0)
    hw.add(cyl(0.06, 0.09, 0.3, hornDarkM, 0, 0, 0.15 * side, 1.35 * side, 0, 0))
    hw.add(cone(0.06, 0.34, hornM, 0, 0.16, 0.3 * side, 0.45 * side, 0, 0))
  }
  // small ears below the horns (extras — spring-follow)
  for (const side of [1, -1]) {
    const ear = pivot(head, -0.02, 0.14, 0.28 * side)
    bones[side === 1 ? 'earL' : 'earR'] = ear
    const ew = bent(ear, 0, 0, -0.5 * side)
    ew.add(sph(0.11, hideM, 0, 0, 0.1 * side, 0.5, 0.75, 1.1))
  }

  if (un) group.scale.setScalar(1.15)

  group.userData.visorMat = visorM
  group.userData.markMats = markMats
  group.userData.baseScale = un ? 1.15 : 1
  group.userData.unchained = un

  group.traverse((o) => {
    if (o.isMesh) { o.castShadow = true; o.receiveShadow = true }
  })

  return { group, bones }
}

