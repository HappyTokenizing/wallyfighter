// ---------------------------------------------------------------------------
// tiny procedural-model helpers (inline — character files are self-contained)
// ---------------------------------------------------------------------------
function lamb(color, opts = {}) {
  return new THREE.MeshLambertMaterial({ color, flatShading: true, ...opts })
}

function box(w, h, d, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function sph(r, material, x = 0, y = 0, z = 0, sx = 1, sy = 1, sz = 1) {
  const m = new THREE.Mesh(new THREE.SphereGeometry(r, 10, 8), material)
  m.position.set(x, y, z)
  m.scale.set(sx, sy, sz)
  return m
}

function cyl(rTop, rBottom, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rTop, rBottom, h, 8, 1), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function cone(r, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.ConeGeometry(r, h, 5), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function pivot(parent, x = 0, y = 0, z = 0) {
  const g = new THREE.Group()
  g.position.set(x, y, z)
  parent.add(g)
  return g
}

// static wrapper: bakes a base rotation between an animated bone and its meshes,
// so every animated bone starts at rotation (0,0,0) = bind pose.
function bent(parent, rz = 0, rx = 0, ry = 0) {
  const g = new THREE.Group()
  g.rotation.set(rx, ry, rz)
  parent.add(g)
  return g
}

// ---------------------------------------------------------------------------
// model — faces +X, feet at y=0, ~1.7 m tall (ears included)
// ---------------------------------------------------------------------------
function buildModel(costume = 0) {
  const group = new THREE.Group()
  const bones = {}

  const night = costume === 1
  const coatM = lamb(night ? C.nightCoat : C.coat)
  const coatLightM = lamb(night ? 0x3a4154 : C.coatLight)
  const creamM = lamb(night ? C.nightCream : C.cream)
  const creamDarkM = lamb(night ? 0xb4bccc : C.creamDark)
  const orangeM = lamb(night ? 0xd9a03f : C.orange)
  const packM = lamb(night ? C.hiVis : C.packOrange)
  const packDarkM = lamb(night ? 0xb8a51c : C.packDark)
  const strapM = lamb(C.strap)
  const noseM = lamb(C.nose)
  const eyeM = lamb(C.eye)
  const bootM = lamb(night ? 0x22242c : C.boot)
  const soleM = lamb(night ? C.hiVis : C.sole)
  const labelM = lamb(C.label)
  if (night) { packM.emissive = new THREE.Color(0x3a3608) } // hi-vis glow

  // --- hips -----------------------------------------------------------------
  const hips = pivot(group, 0, 0.78, 0)
  bones.hips = hips
  hips.add(sph(0.22, coatM, -0.01, 0.01, 0, 1.0, 0.82, 1.05))
  hips.add(sph(0.16, creamM, 0.12, -0.04, 0, 0.7, 0.6, 0.8)) // cream underside

  // tail — NEVER stops wagging (extra bone, fast spring-follow + animated wag)
  const tail = pivot(hips, -0.22, 0.08, 0)
  bones.tail = tail
  const tailW = bent(tail, 2.1)
  tailW.add(cyl(0.05, 0.032, 0.3, coatM, 0, -0.15, 0))
  tailW.add(sph(0.075, creamM, 0, -0.33, 0, 1.0, 1.25, 1.0)) // fluffy cream tip

  // --- legs — springy runner legs with courier sneakers ---------------------
  for (const side of [1, -1]) {
    const leg = pivot(hips, 0, -0.02, 0.13 * side)
    bones[side === 1 ? 'legL' : 'legR'] = leg
    leg.add(sph(0.095, coatM))
    leg.add(cyl(0.085, 0.065, 0.32, coatM, 0, -0.18, 0))
    leg.add(sph(0.06, orangeM, 0.06, -0.12, 0.05 * side, 1.1, 1.4, 0.6)) // tan thigh patch
    const shin = pivot(leg, 0, -0.36, 0)
    bones[side === 1 ? 'shinL' : 'shinR'] = shin
    shin.add(cyl(0.06, 0.05, 0.24, creamM, 0, -0.12, 0)) // cream socks
    shin.add(box(0.24, 0.11, 0.13, bootM, 0.05, -0.305, 0))      // lightweight boot
    shin.add(box(0.27, 0.045, 0.145, soleM, 0.06, -0.375, 0))    // chunky orange sole
    shin.add(box(0.05, 0.05, 0.135, strapM, 0.1, -0.29, 0))      // velcro strap
  }

  // --- torso ---------------------------------------------------------------
  const torso = pivot(hips, 0, 0.1, 0)
  bones.torso = torso
  torso.add(sph(0.3, coatM, 0.02, 0.22, 0, 0.95, 1.05, 0.85))
  torso.add(sph(0.26, creamM, 0.16, 0.14, 0, 0.62, 0.85, 0.62)) // cream chest blaze
  torso.add(sph(0.12, coatLightM, -0.08, 0.36, 0.16, 1.2, 0.8, 0.8)) // shoulder mottle
  torso.add(sph(0.12, coatLightM, -0.06, 0.3, -0.17, 1.1, 0.7, 0.8))

  // courier harness — shoulder straps + chest clasp
  for (const side of [1, -1]) {
    torso.add(box(0.07, 0.4, 0.075, packM, 0.24, 0.28, 0.12 * side, 0.28 * side, 0, -0.35))
    torso.add(box(0.07, 0.34, 0.075, packM, -0.2, 0.3, 0.13 * side, -0.25 * side, 0, 0.5))
  }
  torso.add(box(0.06, 0.11, 0.3, packM, 0.27, 0.14, 0))    // belly band
  torso.add(box(0.05, 0.09, 0.1, strapM, 0.31, 0.32, 0))   // clasp buckle
  torso.add(box(0.052, 0.05, 0.06, labelM, 0.315, 0.15, 0)) // barcode tag

  // small orange backpack (extra bone 'pack' — spring-follow bounce)
  const pack = pivot(torso, -0.26, 0.34, 0)
  bones.pack = pack
  pack.add(box(0.17, 0.32, 0.28, packM, -0.08, -0.06, 0))
  pack.add(box(0.18, 0.1, 0.29, packDarkM, -0.08, 0.09, 0))       // top flap
  pack.add(box(0.05, 0.06, 0.12, strapM, -0.08, 0.16, 0))          // carry handle
  pack.add(box(0.03, 0.1, 0.14, labelM, -0.175, -0.07, 0))         // shipping label
  pack.add(box(0.06, 0.05, 0.05, strapM, -0.11, -0.2, 0.1))        // buckles
  pack.add(box(0.06, 0.05, 0.05, strapM, -0.11, -0.2, -0.1))

  // --- arms ----------------------------------------------------------------
  for (const side of [1, -1]) {
    const arm = pivot(torso, 0.02, 0.38, 0.28 * side)
    bones[side === 1 ? 'armL' : 'armR'] = arm
    arm.add(sph(0.085, coatM))
    arm.add(cyl(0.07, 0.058, 0.2, coatM, 0, -0.11, 0))
    const fore = pivot(arm, 0, -0.23, 0)
    bones[side === 1 ? 'forearmL' : 'forearmR'] = fore
    fore.add(cyl(0.055, 0.05, 0.18, creamM, 0, -0.09, 0))    // cream forelegs
    fore.add(sph(0.08, creamDarkM, 0.015, -0.2, 0, 1.15, 0.85, 1.0)) // paw
    fore.add(box(0.05, 0.05, 0.1, packM, 0, -0.13, 0))       // wristband
  }

  // --- head ----------------------------------------------------------------
  const head = pivot(torso, 0.04, 0.52, 0)
  bones.head = head
  head.add(sph(0.2, coatLightM, 0.03, 0.07, 0, 1.02, 0.95, 1.0))
  head.add(sph(0.17, coatM, -0.01, 0.15, 0, 1.05, 0.75, 1.02)) // dark cap/mask
  // muzzle — cream snout + black nose + happy open jaw
  head.add(sph(0.125, creamM, 0.19, -0.01, 0, 1.35, 0.78, 0.9))
  head.add(sph(0.048, noseM, 0.35, 0.03, 0))
  head.add(box(0.14, 0.035, 0.1, creamDarkM, 0.22, -0.1, 0, 0, 0, 0.15)) // jaw
  head.add(box(0.04, 0.03, 0.04, lamb(0xe0708a), 0.27, -0.085, 0))       // tongue!
  // orange cheek patches + eyebrow dots (classic heeler markings)
  for (const side of [1, -1]) {
    head.add(sph(0.085, orangeM, 0.1, -0.02, 0.14 * side, 0.9, 0.85, 0.5))
    head.add(box(0.035, 0.035, 0.05, orangeM, 0.175, 0.155, 0.075 * side))
    head.add(sph(0.031, eyeM, 0.175, 0.09, 0.085 * side))
  }
  // ears — big upright radar cones (extras earL/earR, spring-follow)
  for (const side of [1, -1]) {
    const ear = pivot(head, -0.03, 0.2, 0.1 * side)
    bones[side === 1 ? 'earL' : 'earR'] = ear
    const w = bent(ear, 0, 0.32 * side, -0.12)
    w.add(cone(0.075, 0.19, coatM, 0, 0.08, 0))
    w.add(cone(0.045, 0.12, creamM, 0.024, 0.065, 0))
    w.add(cone(0.05, 0.06, orangeM, 0, -0.01, 0)) // tan ear base
  }

  group.traverse((o) => {
    if (o.isMesh) { o.castShadow = true; o.receiveShadow = true }
  })

  return { group, bones }
}

