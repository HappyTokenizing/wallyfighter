// ---------------------------------------------------------------------------
// tiny procedural-model helpers (inline — character files are self-contained)
// ---------------------------------------------------------------------------
function lamb(color, opts = {}) {
  return new THREE.MeshLambertMaterial({ color, flatShading: true, ...opts })
}

function box(w, h, d, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function sph(r, material, x = 0, y = 0, z = 0, sx = 1, sy = 1, sz = 1) {
  const m = new THREE.Mesh(new THREE.SphereGeometry(r, 10, 8), material)
  m.position.set(x, y, z)
  m.scale.set(sx, sy, sz)
  return m
}

function cyl(rTop, rBottom, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rTop, rBottom, h, 10, 1), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function pivot(parent, x = 0, y = 0, z = 0) {
  const g = new THREE.Group()
  g.position.set(x, y, z)
  parent.add(g)
  return g
}

// static wrapper: bakes a base rotation between an animated bone and its meshes,
// so every animated bone starts at rotation (0,0,0) = bind pose.
function bent(parent, rz = 0, rx = 0, ry = 0) {
  const g = new THREE.Group()
  g.rotation.set(rx, ry, rz)
  parent.add(g)
  return g
}

// ---------------------------------------------------------------------------
// model — faces +X, feet at y=0, ~2.0 m tall
// ---------------------------------------------------------------------------
function buildModel(costume = 0) {
  const group = new THREE.Group()
  const bones = {}

  const hideM = lamb(C.hide)
  const hideDarkM = lamb(C.hideDark)
  const bellyM = lamb(C.belly)
  const earInM = lamb(C.earInner)
  const tuskM = lamb(C.tusk)
  const nailM = lamb(C.nail)
  const shadeM = lamb(C.shades)
  const lensM = costume === 1
    ? lamb(C.visorGreen, { transparent: true, opacity: 0.85 })
    : lamb(C.shades)
  const markM = lamb(C.mark)
  markM.emissive = new THREE.Color(0x333333)

  // --- hips -----------------------------------------------------------------
  const hips = pivot(group, 0, 0.92, 0)
  bones.hips = hips
  hips.add(sph(0.34, hideM, 0, 0.02, 0, 1.0, 0.78, 1.06))

  // tail (extra bone, spring-follow secondary motion)
  const tail = pivot(hips, -0.30, 0.06, 0)
  bones.tail = tail
  const tailW = bent(tail, 2.35)
  tailW.add(cyl(0.035, 0.022, 0.3, hideM, 0, -0.15, 0))
  tailW.add(sph(0.05, hideDarkM, 0, -0.31, 0))

  // --- legs (chunky columns with toenails) ---------------------------------
  for (const side of [1, -1]) {
    const leg = pivot(hips, 0, -0.02, 0.20 * side)
    bones[side === 1 ? 'legL' : 'legR'] = leg
    leg.add(cyl(0.17, 0.19, 0.62, hideM, 0, -0.33, 0))
    leg.add(cyl(0.20, 0.22, 0.18, hideDarkM, 0.03, -0.81, 0))
    for (let i = -1; i <= 1; i++) leg.add(box(0.07, 0.07, 0.07, nailM, 0.23, -0.86, i * 0.1))
  }

  // --- torso ---------------------------------------------------------------
  const torso = pivot(hips, 0, 0.10, 0)
  bones.torso = torso
  torso.add(sph(0.5, hideM, 0.02, 0.26, 0, 0.98, 1.02, 0.92))
  torso.add(sph(0.42, bellyM, 0.26, 0.14, 0, 0.62, 0.86, 0.72)) // lighter belly plate

  // costume 1: gold chain + pendant
  if (costume === 1) {
    const goldM = lamb(C.gold)
    goldM.emissive = new THREE.Color(0x332200)
    for (let i = 0; i < 10; i++) {
      const a = (i / 10) * Math.PI * 2
      torso.add(sph(0.05, goldM, 0.04 + Math.cos(a) * 0.34, 0.52 - Math.cos(a) * 0.09, Math.sin(a) * 0.30))
    }
    const pend = box(0.05, 0.17, 0.15, goldM, 0.42, 0.36, 0)
    torso.add(pend)
    torso.add(box(0.052, 0.1, 0.03, lamb(C.mark), 0.425, 0.36, 0)) // "W" bar on the pendant
  }

  // --- arms ----------------------------------------------------------------
  for (const side of [1, -1]) {
    const arm = pivot(torso, 0.02, 0.42, 0.46 * side)
    bones[side === 1 ? 'armL' : 'armR'] = arm
    arm.add(sph(0.135, hideM))
    arm.add(cyl(0.11, 0.10, 0.30, hideM, 0, -0.17, 0))
    const fore = pivot(arm, 0, -0.34, 0)
    bones[side === 1 ? 'forearmL' : 'forearmR'] = fore
    fore.add(cyl(0.10, 0.09, 0.26, hideM, 0, -0.13, 0))
    fore.add(sph(0.13, hideDarkM, 0.02, -0.30, 0, 1.1, 0.9, 1.0)) // mitten hand
  }

  // --- head ----------------------------------------------------------------
  const head = pivot(torso, 0.06, 0.62, 0)
  bones.head = head
  head.add(sph(0.33, hideM, 0.06, 0.08, 0, 1.02, 0.96, 1.0))
  head.add(sph(0.20, hideM, -0.10, 0.24, 0, 1.0, 0.8, 1.1)) // dome bump

  // ears — big round fans, swept slightly back (extras earL/earR)
  for (const side of [1, -1]) {
    const ear = pivot(head, -0.04, 0.14, 0.26 * side)
    bones[side === 1 ? 'earL' : 'earR'] = ear
    const w = bent(ear, 0, 0, -0.35 * side)
    w.add(sph(0.32, hideM, -0.02, -0.02, 0.24 * side, 0.18, 1.0, 0.85))
    w.add(sph(0.32, earInM, 0.035, -0.02, 0.24 * side, 0.09, 0.8, 0.66))
  }

  // trunk — 3-segment chain, curve baked into static wrappers so the animated
  // bones (trunk/trunk2/trunk3) all start at zero rotation.
  const trunk = pivot(head, 0.28, -0.04, 0)
  bones.trunk = trunk
  const s1 = bent(trunk, 0.85)
  s1.add(cyl(0.105, 0.09, 0.30, hideM, 0, -0.15, 0))
  const trunk2 = pivot(s1, 0, -0.30, 0)
  bones.trunk2 = trunk2
  const s2 = bent(trunk2, -0.55)
  s2.add(cyl(0.09, 0.075, 0.26, hideM, 0, -0.13, 0))
  const trunk3 = pivot(s2, 0, -0.26, 0)
  bones.trunk3 = trunk3
  const s3 = bent(trunk3, -0.7)
  s3.add(cyl(0.075, 0.06, 0.22, hideM, 0, -0.11, 0))
  s3.add(cyl(0.062, 0.075, 0.07, hideDarkM, 0, -0.24, 0)) // nostril tip

  // tusks — cream, forward-up
  for (const side of [1, -1]) {
    const tw = bent(pivot(head, 0.22, -0.16, 0.14 * side), -1.25, 0.16 * side)
    tw.add(cyl(0.028, 0.06, 0.30, tuskM, 0, 0.15, 0))
  }

  // --- SUNGLASSES with rising-chart zigzag mark ----------------------------
  head.add(box(0.06, 0.045, 0.46, shadeM, 0.38, 0.16, 0)) // top bar
  head.add(box(0.05, 0.03, 0.1, shadeM, 0.4, 0.12, 0)) // bridge over trunk
  const lensMats = []
  for (const side of [1, -1]) {
    head.add(box(0.06, 0.19, 0.19, lensM, 0.40, 0.095, 0.13 * side))
    // rising chart: three white ticks, each higher than the last (dip in the middle)
    head.add(box(0.014, 0.02, 0.075, markM, 0.435, 0.055, 0.185 * side, 0.7 * side))
    head.add(box(0.014, 0.02, 0.06, markM, 0.435, 0.09, 0.128 * side, -0.85 * side))
    head.add(box(0.014, 0.02, 0.08, markM, 0.435, 0.135, 0.072 * side, 0.8 * side))
    head.add(box(0.26, 0.032, 0.032, shadeM, 0.24, 0.15, 0.235 * side)) // temple arm
  }
  lensMats.push(lensM)
  head.userData.lensMats = lensMats
  head.userData.lensBaseHex = lensM.color.getHex()
  head.userData.markMat = markM

  group.traverse((o) => {
    if (o.isMesh) { o.castShadow = true; o.receiveShadow = true }
  })

  return { group, bones }
}

