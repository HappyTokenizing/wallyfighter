import * as THREE from 'three'

// ---------------------------------------------------------------------------
// Model helpers (local to this file)
// ---------------------------------------------------------------------------
function makeMat(color) {
  return new THREE.MeshLambertMaterial({ color, flatShading: true })
}

function addBox(parent, w, h, d, color, x = 0, y = 0, z = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), makeMat(color))
  m.position.set(x, y, z)
  parent.add(m)
  return m
}

function addSphere(parent, r, color, x = 0, y = 0, z = 0, seg = 6) {
  const m = new THREE.Mesh(new THREE.SphereGeometry(r, seg, Math.max(4, seg - 1)), makeMat(color))
  m.position.set(x, y, z)
  parent.add(m)
  return m
}

function addPivot(parent, x = 0, y = 0, z = 0) {
  const g = new THREE.Group()
  g.position.set(x, y, z)
  parent.add(g)
  return g
}

