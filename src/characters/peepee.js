// ---------------------------------------------------------------------------
// tiny procedural-model helpers (inline — character files are self-contained)
// ---------------------------------------------------------------------------
function lamb(color, opts = {}) {
  return new THREE.MeshLambertMaterial({ color, flatShading: true, ...opts })
}

function box(w, h, d, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function sph(r, material, x = 0, y = 0, z = 0, sx = 1, sy = 1, sz = 1) {
  const m = new THREE.Mesh(new THREE.SphereGeometry(r, 10, 8), material)
  m.position.set(x, y, z)
  m.scale.set(sx, sy, sz)
  return m
}

function cyl(rTop, rBottom, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rTop, rBottom, h, 10, 1), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function pivot(parent, x = 0, y = 0, z = 0) {
  const g = new THREE.Group()
  g.position.set(x, y, z)
  parent.add(g)
  return g
}

// static wrapper: bakes a base rotation between an animated bone and its meshes,
// so every animated bone starts at rotation (0,0,0) = bind pose.
function bent(parent, rz = 0, rx = 0, ry = 0) {
  const g = new THREE.Group()
  g.rotation.set(rx, ry, rz)
  parent.add(g)
  return g
}

// ---------------------------------------------------------------------------
// model — faces +X, feet at y=0, ~1.5 m tall squat frog
// ---------------------------------------------------------------------------
function buildModel(costume = 0) {
  const group = new THREE.Group()
  const bones = {}

  const frogM = lamb(C.frog)
  const frogDarkM = lamb(C.frogDark)
  const bellyM = lamb(C.belly)
  const lipM = lamb(C.lip)
  const eyeM = lamb(C.eyeWhite)
  const pupilM = lamb(C.pupil)
  const tongueM = lamb(C.tongue)
  const jacketM = lamb(costume === 1 ? C.jacketAlt : C.jacket)
  const goldM = lamb(C.gold)
  goldM.emissive = new THREE.Color(0x2e2205)
  const goldDarkM = lamb(C.goldDark)

  // --- hips -----------------------------------------------------------------
  const hips = pivot(group, 0, 0.62, 0)
  bones.hips = hips
  hips.add(sph(0.27, frogM, -0.02, 0.0, 0, 1.05, 0.8, 1.2))

  // --- legs — short elastic haunches with big webbed feet --------------------
  for (const side of [1, -1]) {
    const leg = pivot(hips, -0.02, -0.06, 0.17 * side)
    bones[side === 1 ? 'legL' : 'legR'] = leg
    leg.add(sph(0.13, frogM, 0, -0.05, 0.02 * side, 1.0, 1.1, 1.0)) // haunch
    leg.add(cyl(0.09, 0.08, 0.24, frogM, 0, -0.16, 0))
    const shin = pivot(leg, 0, -0.28, 0)
    bones[side === 1 ? 'shinL' : 'shinR'] = shin
    shin.add(cyl(0.075, 0.07, 0.24, frogM, 0, -0.12, 0))
    // huge webbed foot: flat pad + three splayed toes
    shin.add(box(0.24, 0.055, 0.16, frogDarkM, 0.1, -0.26, 0))
    for (let i = -1; i <= 1; i++) {
      shin.add(box(0.14, 0.05, 0.05, frogDarkM, 0.26, -0.26, i * 0.07, 0, i * 0.35))
      shin.add(sph(0.035, frogDarkM, 0.33, -0.26, i * 0.09))
    }
  }

  // --- torso — round belly in a short open jacket ----------------------------
  const torso = pivot(hips, 0, 0.04, 0)
  bones.torso = torso
  torso.add(sph(0.36, frogM, 0.0, 0.22, 0, 1.02, 0.95, 1.12))
  torso.add(sph(0.32, bellyM, 0.14, 0.16, 0, 0.72, 0.82, 0.8)) // pale throat/belly

  // short jacket: back panel + two front lapel panels + collar (ends high)
  torso.add(box(0.16, 0.42, 0.62, jacketM, -0.26, 0.3, 0))
  torso.add(box(0.3, 0.4, 0.1, jacketM, 0.1, 0.32, 0.31, 0, -0.25))
  torso.add(box(0.3, 0.4, 0.1, jacketM, 0.1, 0.32, -0.31, 0, 0.25))
  torso.add(box(0.12, 0.09, 0.5, jacketM, 0.16, 0.5, 0)) // collar
  if (costume === 1) {
    // swamp tuxedo: gold pocket square + lapel pins
    torso.add(box(0.04, 0.09, 0.07, goldM, 0.26, 0.4, 0.28))
    torso.add(sph(0.03, goldM, 0.26, 0.52, -0.24))
  }

  // --- OVERSIZED gold tie (extra bone, springy secondary motion) -------------
  const tie = pivot(torso, 0.3, 0.44, 0)
  bones.tie = tie
  const tieW = bent(tie, -0.18) // drapes slightly forward off the belly
  tieW.add(box(0.09, 0.11, 0.13, goldDarkM, 0, -0.04, 0)) // knot
  tieW.add(box(0.07, 0.34, 0.24, goldM, 0.015, -0.28, 0)) // blade top
  tieW.add(box(0.07, 0.26, 0.3, goldM, 0.03, -0.55, 0)) // blade wide middle
  // pointed tip: two angled slabs
  tieW.add(box(0.07, 0.16, 0.17, goldM, 0.04, -0.72, 0.07, 0.5))
  tieW.add(box(0.07, 0.16, 0.17, goldM, 0.04, -0.72, -0.07, -0.5))
  tieW.add(box(0.075, 0.1, 0.1, goldDarkM, 0.03, -0.5, 0, 0, 0, 0.78)) // $ glint

  // --- arms — short, elastic, jacket sleeves ---------------------------------
  for (const side of [1, -1]) {
    const arm = pivot(torso, 0.02, 0.4, 0.32 * side)
    bones[side === 1 ? 'armL' : 'armR'] = arm
    arm.add(sph(0.095, jacketM))
    arm.add(cyl(0.08, 0.075, 0.18, jacketM, 0, -0.1, 0))
    const fore = pivot(arm, 0, -0.2, 0)
    bones[side === 1 ? 'forearmL' : 'forearmR'] = fore
    fore.add(cyl(0.07, 0.06, 0.16, frogM, 0, -0.08, 0))
    fore.add(sph(0.085, frogM, 0.01, -0.18, 0, 1.15, 0.8, 1.1)) // sticky pad hand
    for (let i = -1; i <= 1; i++) fore.add(sph(0.03, frogM, 0.08, -0.2, i * 0.05))
  }

  // --- head — wide, flat, mostly mouth ---------------------------------------
  const head = pivot(torso, 0.05, 0.52, 0)
  bones.head = head
  head.add(sph(0.3, frogM, 0.05, 0.06, 0, 1.05, 0.78, 1.25))
  head.add(sph(0.24, bellyM, 0.14, -0.05, 0, 0.9, 0.6, 1.0)) // pale chin/throat

  // WIDE mouth: dark lip line + upturned grin corners
  head.add(box(0.05, 0.035, 0.5, lipM, 0.3, -0.03, 0))
  head.add(box(0.05, 0.035, 0.12, lipM, 0.24, 0.0, 0.28, 0, 0.65))
  head.add(box(0.05, 0.035, 0.12, lipM, 0.24, 0.0, -0.28, 0, -0.65))

  // tongue (extra bone) — tucked under the chin at bind pose, thrusts out in moves
  const tongue = pivot(head, 0.2, -0.06, 0)
  bones.tongue = tongue
  const tongueW = bent(tongue, 0.85) // bake the tuck; bone zero = hidden
  tongueW.add(box(0.3, 0.05, 0.12, tongueM, 0.13, 0, 0))
  tongueW.add(sph(0.07, tongueM, 0.3, 0, 0, 1.0, 0.7, 1.1))

  // --- LARGE animated eyes (extra bones eyeL/eyeR) ---------------------------
  for (const side of [1, -1]) {
    const eye = pivot(head, 0.06, 0.24, 0.16 * side)
    bones[side === 1 ? 'eyeL' : 'eyeR'] = eye
    eye.add(sph(0.115, eyeM))
    eye.add(sph(0.048, pupilM, 0.09, 0.01, 0)) // pupil forward — eye rot swivels gaze
    eye.add(box(0.14, 0.05, 0.2, frogM, -0.01, 0.1, 0, 0, 0, -0.15)) // heavy lid
    if (costume === 1 && side === -1) {
      // gold monocle on the right eye + chain hint
      const ring = new THREE.Mesh(new THREE.TorusGeometry(0.11, 0.018, 6, 12), goldM)
      ring.rotation.y = Math.PI / 2
      ring.position.set(0.1, 0, 0)
      eye.add(ring)
      eye.add(box(0.02, 0.16, 0.02, goldM, 0.08, -0.14, -0.04, 0.3))
    }
  }

  if (costume === 1) {
    // tiny "market maker" top hat, absurdly small
    head.add(cyl(0.11, 0.11, 0.14, lamb(C.jacket), -0.04, 0.36, 0))
    head.add(cyl(0.17, 0.17, 0.03, lamb(C.jacket), -0.04, 0.3, 0))
    head.add(box(0.02, 0.05, 0.24, goldM, -0.04 + 0.1, 0.33, 0))
  }

  group.traverse((o) => {
    if (o.isMesh) { o.castShadow = true; o.receiveShadow = true }
  })

  return { group, bones }
}

