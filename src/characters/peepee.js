  const eyeGeo = new THREE.BoxGeometry(0.05, 0.05, 0.05)
  const frogMat = new THREE.MeshLambertMaterial({ color: C.frog, flatShading: true })
  const eyeMat = new THREE.MeshLambertMaterial({ color: C.eyeWhite, flatShading: true })
