// ---------------------------------------------------------------------------
// tiny procedural-model helpers (inline — character files are self-contained)
// ---------------------------------------------------------------------------
function lamb(color, opts = {}) {
  return new THREE.MeshLambertMaterial({ color, flatShading: true, ...opts })
}

function box(w, h, d, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function sph(r, material, x = 0, y = 0, z = 0, sx = 1, sy = 1, sz = 1) {
  const m = new THREE.Mesh(new THREE.SphereGeometry(r, 10, 8), material)
  m.position.set(x, y, z)
  m.scale.set(sx, sy, sz)
  return m
}

function cyl(rTop, rBottom, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0, seg = 10) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rTop, rBottom, h, seg, 1), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function cone(r, h, material, x = 0, y = 0, z = 0, rx = 0, ry = 0, rz = 0, seg = 4) {
  const m = new THREE.Mesh(new THREE.ConeGeometry(r, h, seg), material)
  m.position.set(x, y, z)
  m.rotation.set(rx, ry, rz)
  return m
}

function pivot(parent, x = 0, y = 0, z = 0) {
  const g = new THREE.Group()
  g.position.set(x, y, z)
  parent.add(g)
  return g
}

// static wrapper: bakes a base rotation between an animated bone and its
// meshes, so every animated bone starts at rotation (0,0,0) = bind pose.
function bent(parent, rz = 0, rx = 0, ry = 0) {
  const g = new THREE.Group()
  g.rotation.set(rx, ry, rz)
  parent.add(g)
  return g
}

// ---------------------------------------------------------------------------
// model — faces +X, feet at y=0, ~1.9 m tall
// ---------------------------------------------------------------------------
function buildModel(costume = 0) {
  const group = new THREE.Group()
  const bones = {}

  const furM = lamb(C.fur)
  const furShadeM = lamb(C.furShade)
  const creamM = lamb(C.cream)
  const innerM = lamb(C.earInner)
  const darkM = lamb(C.dark)
  const armorM = lamb(costume === 1 ? C.armorNight : C.armor)
  const armorDarkM = lamb(costume === 1 ? 0x2c3340 : C.armorDark)
  const sashM = lamb(costume === 1 ? C.sashNight : C.sashBlue)
  const goldM = lamb(C.gold)
  goldM.emissive = new THREE.Color(0x2a1d00)

  // --- hips -----------------------------------------------------------------
  const hips = pivot(group, 0, 1.0, 0)
  bones.hips = hips
  hips.add(sph(0.28, furM, 0, 0.02, 0, 1.0, 0.8, 1.02))

  // waist sash band (static) + hanging sash panel (extra bone, spring-follow)
  hips.add(box(0.5, 0.12, 0.52, sashM, 0.01, 0.1, 0))
  const sash = pivot(hips, -0.06, 0.04, 0.24)
  bones.sash = sash
  const sashW = bent(sash, 0, 0.18, 0.1)
  sashW.add(box(0.06, 0.44, 0.17, sashM, 0, -0.24, 0.02))
  sashW.add(box(0.062, 0.07, 0.175, goldM, 0, -0.44, 0.02)) // gold-tipped hem

  // curled spitz tail (extra bone, spring-follow)
  const tail = pivot(hips, -0.26, 0.1, 0)
  bones.tail = tail
  const tailW = bent(tail, -2.3)
  tailW.add(cyl(0.06, 0.045, 0.28, furM, 0, -0.14, 0))
  tailW.add(sph(0.1, creamM, 0, -0.3, 0, 1.0, 1.2, 0.9))

  // --- legs — clean columns with neat paws ----------------------------------
  for (const side of [1, -1]) {
    const leg = pivot(hips, 0, -0.02, 0.17 * side)
    bones[side === 1 ? 'legL' : 'legR'] = leg
    leg.add(sph(0.13, furM))
    leg.add(cyl(0.12, 0.105, 0.5, furM, 0, -0.27, 0))
    const shin = pivot(leg, 0, -0.52, 0)
    bones[side === 1 ? 'shinL' : 'shinR'] = shin
    shin.add(cyl(0.1, 0.085, 0.4, furM, 0, -0.21, 0))
    shin.add(box(0.3, 0.13, 0.18, creamM, 0.08, -0.4, 0))
    for (let i = -1; i <= 1; i++) shin.add(box(0.05, 0.05, 0.04, darkM, 0.23, -0.42, i * 0.06))
  }

  // --- torso ---------------------------------------------------------------
  const torso = pivot(hips, 0, 0.12, 0)
  bones.torso = torso
  torso.add(sph(0.4, furM, 0.02, 0.28, 0, 0.95, 1.05, 0.85))
  torso.add(sph(0.32, creamM, 0.24, 0.2, 0, 0.62, 0.95, 0.72)) // chest fluff

  // silver low-poly shoulder armor (mounted on the torso, above the arm pivots)
  for (const side of [1, -1]) {
    torso.add(box(0.3, 0.1, 0.3, armorM, 0.02, 0.56, 0.34 * side, 0.28 * side))
    torso.add(box(0.26, 0.09, 0.26, armorM, 0.02, 0.48, 0.4 * side, 0.42 * side))
    torso.add(box(0.2, 0.08, 0.2, armorDarkM, 0.02, 0.4, 0.45 * side, 0.55 * side))
    torso.add(box(0.05, 0.05, 0.05, goldM, 0.02, 0.6, 0.34 * side)) // rivet
  }
  // armor chest strap
  torso.add(box(0.34, 0.09, 0.06, armorDarkM, 0.3, 0.42, 0, 0, 0, -0.5))
  torso.add(box(0.34, 0.09, 0.06, armorDarkM, 0.3, 0.42, 0, 0, 0, 0.5))

  // geometric gold medallion — hexagonal seal on a cord
  for (const side of [1, -1]) {
    torso.add(box(0.03, 0.24, 0.03, goldM, 0.22, 0.5, 0.12 * side, 0.42 * side, 0, -0.35))
  }
  const medal = new THREE.Mesh(new THREE.CylinderGeometry(0.11, 0.11, 0.035, 6, 1), goldM)
  medal.position.set(0.36, 0.3, 0)
  medal.rotation.z = Math.PI / 2
  torso.add(medal)
  const medalCore = cone(0.055, 0.05, darkM, 0.385, 0.3, 0, 0, 0, -Math.PI / 2, 3)
  torso.add(medalCore)
  torso.userData.medalMat = goldM

  // --- arms ----------------------------------------------------------------
  for (const side of [1, -1]) {
    const arm = pivot(torso, 0.02, 0.42, 0.34 * side)
    bones[side === 1 ? 'armL' : 'armR'] = arm
    arm.add(sph(0.11, furM))
    arm.add(cyl(0.09, 0.082, 0.3, furM, 0, -0.16, 0))
    const fore = pivot(arm, 0, -0.32, 0)
    bones[side === 1 ? 'forearmL' : 'forearmR'] = fore
    fore.add(cyl(0.078, 0.07, 0.24, furM, 0, -0.12, 0))
    fore.add(sph(0.105, creamM, 0.02, -0.27, 0, 1.1, 0.9, 1.0)) // paw

    // right forearm carries the (hidden) energy blade for slashes/super
    if (side === -1) {
      const blade = new THREE.Group()
      const bladeM = lamb(C.blade, { transparent: true, opacity: 0.8 })
      bladeM.emissive = new THREE.Color(0x0b96a8)
      const coreM = lamb(C.bladeCore, { transparent: true, opacity: 0.9 })
      coreM.emissive = new THREE.Color(0x9adfe8)
      blade.add(box(0.05, 0.95, 0.2, bladeM, 0.02, -0.76, 0))
      blade.add(box(0.03, 0.85, 0.09, coreM, 0.025, -0.74, 0))
      blade.add(cone(0.1, 0.22, bladeM, 0.02, -1.32, 0, Math.PI))
      blade.visible = false
      fore.add(blade)
      fore.userData.blade = blade
      fore.userData.bladeMats = [bladeM, coreM]
    }
  }

  // --- head ----------------------------------------------------------------
  const head = pivot(torso, 0.05, 0.5, 0)
  bones.head = head
  head.add(sph(0.26, furM, 0.02, 0.08, 0, 1.0, 0.95, 0.98))
  head.add(sph(0.12, creamM, 0.1, -0.02, 0.17, 1, 0.9, 0.8)) // cheek fluff
  head.add(sph(0.12, creamM, 0.1, -0.02, -0.17, 1, 0.9, 0.8))
  head.add(box(0.28, 0.15, 0.19, furM, 0.26, -0.01, 0))
  head.add(box(0.1, 0.1, 0.14, creamM, 0.28, -0.09, 0)) // chin
  head.add(box(0.08, 0.07, 0.09, darkM, 0.41, 0.02, 0)) // nose
  // calm, steady eyes
  head.add(box(0.05, 0.09, 0.07, darkM, 0.23, 0.14, 0.12))
  head.add(box(0.05, 0.09, 0.07, darkM, 0.23, 0.14, -0.12))
  head.add(box(0.06, 0.025, 0.09, furShadeM, 0.24, 0.21, 0.12, -0.15)) // noble brows
  head.add(box(0.06, 0.025, 0.09, furShadeM, 0.24, 0.21, -0.12, 0.15))

  // tall pointed ears (extra bones earL/earR, spring-follow)
  for (const side of [1, -1]) {
    const ear = pivot(head, -0.03, 0.27, 0.13 * side)
    bones[side === 1 ? 'earL' : 'earR'] = ear
    const w = bent(ear, 0, 0.22 * side, -0.06)
    w.add(cone(0.095, 0.34, furM, 0, 0.15, 0))
    w.add(cone(0.055, 0.22, innerM, 0.035, 0.11, 0))
  }

  group.traverse((o) => {
    if (o.isMesh) { o.castShadow = true; o.receiveShadow = true }
  })

  return { group, bones }
}

